import nextEnv from '@next/env';
const {loadEnvConfig}=nextEnv;
import {neon} from '@neondatabase/serverless';
import {randomBytes} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
loadEnvConfig(process.cwd());
const admin=process.env.DATABASE_URL_UNPOOLED;
if(!admin)throw Error('Migration connection required.');
const sql=neon(admin);const password=randomBytes(36).toString('hex');
const roles=await sql`SELECT rolname FROM pg_roles WHERE rolname='launchcheck_runtime'`;
if(!roles.length)await sql.query(`CREATE ROLE launchcheck_runtime LOGIN PASSWORD '${password}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS`);
else throw Error('Runtime role already exists; refusing to rotate it implicitly.');
await sql.query('GRANT USAGE ON SCHEMA public TO launchcheck_runtime');
await sql.query('GRANT SELECT, INSERT, UPDATE ON scans TO launchcheck_runtime');
await sql.query('GRANT SELECT, INSERT ON purchases TO launchcheck_runtime');
await sql.query('GRANT SELECT, INSERT, UPDATE, DELETE ON rate_limits TO launchcheck_runtime');
const url=new URL(process.env.DATABASE_URL);url.username='launchcheck_runtime';url.password=password;
const file=await readFile('.env.local','utf8');await writeFile('.env.local',file.replace(/^DATABASE_URL=.*$/m,`DATABASE_URL="${url.href}"`),{mode:0o600});
console.log('Created least-privilege runtime role and updated local runtime connection.');
